/** 궁합 UI는 `lib/gunghap.ts` 전용 카피를 사용. 참고·검증용으로만 유지 */
export function meetingCopy(
  selfGod: string,
  otherGod: string,
): { lead: string; focus: string; action: string; caution: string; keyword: string } {
  const tone = meetingTone(selfGod, otherGod);
  const focus = `나는 ${tenGodPlain(selfGod)}, 상대는 ${tenGodPlain(otherGod)} 쪽에 힘이 실립니다(${selfGod}·${otherGod}).`;
  if (tone === '주의') {
    return {
      lead: '오늘은 말과 거리가 예민해지기 쉬운 흐름입니다.',
      focus,
      action: '결론을 서두르지 말고, 짧은 안부만 나누세요.',
      caution: '단정적인 표현과 비교·재촉은 잠시 미루세요.',
      keyword: '호흡',
    };
  }
  if (tone === '조율') {
    return {
      lead: '오늘은 속도가 다를 수 있어, 한 박자 늦추면 편합니다.',
      focus,
      action: '상대의 페이스를 한 번 확인하고 약속을 잡으세요.',
      caution: '내 기준으로만 밀어붙이지 마세요.',
      keyword: '조율',
    };
  }
  return {
    lead: '오늘은 서로의 속도를 맞추기 쉬운 흐름입니다.',
    focus,
    action: '미뤄 둔 연락이나 작은 호의를 먼저 건네 보세요.',
    caution: '기분이 좋다고 약속을 과하게 늘리지 마세요.',
    keyword: '맞춤',
  };
}
