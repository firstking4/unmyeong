const HARD_GODS = new Set(['겁재', '상관', '편관']);

export type MeetingTone = '순조' | '조율' | '주의';

export function meetingTone(selfGod: string, otherGod: string): MeetingTone {
  const selfHard = HARD_GODS.has(selfGod);
  const otherHard = HARD_GODS.has(otherGod);
  if (selfHard && otherHard) return '주의';
  if (selfHard || otherHard) return '조율';
  return '순조';
}

