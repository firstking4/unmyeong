/**
 * 타로 도감·스프레드 칩 톤.
 * 분명한 긍정(파랑)·부정(주홍)만 가리고, 애매한 말은 일반(회색).
 */
export function tarotKeywordTone(label: string): KeywordTone {
  const text = label.trim();
  if (!text) return 'neutral';
  if (NEGATIVE.has(text) || text.includes('주의') || text.includes('지연')) return 'negative';
  if (POSITIVE.has(text)) return 'positive';
  return 'neutral';
}
