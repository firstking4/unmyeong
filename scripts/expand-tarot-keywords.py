def uniq(words: list[str]) -> list[str]:
    out: list[str] = []
    for w in words:
        w = w.strip()
        if w and w not in out:
            out.append(w)
    return out


def main() -> None:
    bad = []
    for cid, words in KW.items():
        u = uniq(words)
        if not (8 <= len(u) <= 12):
            # allow sun (6) and a few short ones; clamp soft
            if len(u) < 6 or len(u) > 14:
                bad.append((cid, len(u), u))
        KW[cid] = u
    if bad:
        raise SystemExit(f"keyword length out of range: {bad}")

    for name in ("tarot-major.json", "tarot-minor.json"):
        path = ROOT / "data/seed" / name
        data = json.loads(path.read_text(encoding="utf-8"))
        missing = []
        for item in data["items"]:
            cid = item["id"]
            if cid not in KW:
                missing.append(cid)
                continue
            item["keywords"] = KW[cid]
        if missing:
            raise SystemExit(f"{name} missing: {missing}")
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    lens = [len(v) for v in KW.values()]
    print(f"updated {len(KW)} cards; keyword counts min={min(lens)} max={max(lens)} avg={sum(lens)/len(lens):.1f}")


if __name__ == "__main__":
    main()
