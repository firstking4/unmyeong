def patch(path: Path) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    missing = []
    for item in data["items"]:
        uid = item["id"]
        if uid not in UPDATES:
            missing.append(uid)
            continue
        patch_body = UPDATES[uid]
        item["keywords"] = patch_body["keywords"]
        item["summary"] = patch_body["summary"]
        item["upright"] = patch_body["upright"]
        item["reversed"] = patch_body["reversed"]
        item["hints"] = patch_body["hints"]
    if missing:
        raise SystemExit(f"{path.name} missing updates: {missing}")
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    expected = 22 + 56
    if len(UPDATES) != expected:
        raise SystemExit(f"expected {expected} updates, got {len(UPDATES)}")
    patch(ROOT / "data/seed/tarot-major.json")
    patch(ROOT / "data/seed/tarot-minor.json")
    print(f"patched {len(UPDATES)} cards")


if __name__ == "__main__":
    main()
